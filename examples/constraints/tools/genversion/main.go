// Command genversion writes a Go file that defines the version.
package main

import (
	"flag"
	"fmt"
	"os"
)

func main() {
	out := flag.String("o", "version_gen.go", "output file")
	flag.Parse()
	src := "// Code generated by genversion. DO NOT EDIT.\n\npackage version\n\nconst generated = \"v1.0.0\"\n"
	if err := os.WriteFile(*out, []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
